#!/usr/bin/env python3
"""
Generate BMP wcwidth tables from the Unicode 17.0.0 character database.

Download UnicodeData.txt and EastAsianWidth.txt from
https://www.unicode.org/Public/17.0.0/ucd/ and run:
    python3 gen_wcwidth.py UnicodeData.txt EastAsianWidth.txt > locale_wcwidth.c

Python and the input files are needed only to regenerate the checked-in tables.
"""

import argparse
import hashlib
from pathlib import Path


def read_data(path, checksum):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != checksum:
        raise ValueError("Unexpected Unicode 17.0.0 input: " + str(path))
    return data.decode("utf-8")


def intervals(points):
    result = []
    for point in sorted(points):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("unicode_data", type=Path)
    parser.add_argument("east_asian_width", type=Path)
    args = parser.parse_args()
    data = read_data(args.unicode_data,
                     "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c")
    widths = read_data(args.east_asian_width,
                       "ea7ce50f3444a050333448dffef1cadd9325af55cbb764b4a2280faf52170a33")

    zero = set()
    for line in data.splitlines():
        fields = line.split(";")
        point = int(fields[0], 16)
        if point <= 0xffff and fields[2] in ("Mn", "Me", "Cf"):
            zero.add(point)
    # Soft hyphen occupies a cell. Hangul medial/final Jamo combine with
    # the leading Jamo, including their Extended-B counterparts.
    zero.discard(0x00ad)
    zero.update(range(0x1160, 0x1200))
    zero.update(range(0xd7b0, 0xd7c7))
    zero.update(range(0xd7cb, 0xd7fc))

    wide = set()
    for line in widths.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        codepoints, width = (field.strip() for field in line.split(";"))
        if width not in ("W", "F"):
            continue
        bounds = codepoints.split("..")
        first, last = int(bounds[0], 16), int(bounds[-1], 16)
        wide.update(range(first, min(last, 0xffff) + 1))
    # Zero width takes precedence over East Asian Width (e.g. U+302A).
    wide.difference_update(zero)

    print("""/*
 * Generated by gen_wcwidth.py from Unicode 17.0.0; do not edit.
 * Sources: https://www.unicode.org/Public/17.0.0/ucd/UnicodeData.txt
 *          https://www.unicode.org/Public/17.0.0/ucd/EastAsianWidth.txt
 * Unicode data copyright and permission notice: see UNICODE-LICENSE.txt.
 *
 * OS/2 wchar_t is 16 bits, so these tables cover the BMP only.
 * Zero width: Mn, Me, Cf except U+00AD, plus Hangul medial/final Jamo.
 * Double width: East_Asian_Width W/F, excluding zero-width characters.
 * Ambiguous characters retain the ordinary single-cell fallback.
 */

#include <InnoTekLIBC/locale.h>

const __LIBC_LOCALEWCWIDTH __libc_gaLocaleWCWidth[] =
{
""")
    ranges = [(first, last, "__CT_SCRW0") for first, last in intervals(zero)]
    ranges += [(first, last, "__CT_SCRW2") for first, last in intervals(wide)]
    for first, last, width in sorted(ranges):
        print("    { 0x%04x, 0x%04x, %s }," % (first, last, width))
    print("""};

const size_t __libc_gcLocaleWCWidth =
    sizeof(__libc_gaLocaleWCWidth) / sizeof(__libc_gaLocaleWCWidth[0]);""")


if __name__ == "__main__":
    main()
